//! Codes registry generation through the real binary: generate, check, drift.

use std::fs;
use std::path::Path;
use std::process::{Command, Output};

fn run(root: &Path, args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_rekon"))
        .current_dir(root)
        .args(args)
        .output()
        .unwrap()
}

fn success(output: Output) -> Output {
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    output
}

#[test]
fn codes_generates_checks_and_fails_loudly_on_drift() {
    let fixture = tempfile::tempdir().unwrap();
    let root = fixture.path();
    fs::create_dir_all(root.join("codes")).unwrap();
    fs::write(
        root.join("codes/g.md"),
        "---\ncode: g\ntarget: /constitution/structure.md#global\ndescription: Global guidance.\n---\n\n# g\n\nnotes\n",
    )
    .unwrap();
    fs::write(
        root.join("codes/cf.md"),
        "---\ncode: cf\ntarget: file:///home/rektide/src/compfuzor/README.md\ndescription: Compfuzor; not Cloudflare.\n---\n\n# cf\n\nnotes\n",
    )
    .unwrap();

    success(run(root, &["codes"]));
    let registry = fs::read_to_string(root.join("codes.md")).unwrap();
    assert!(registry.contains("generated by Rust `rekon codes`"));
    let cf = registry.find("| `cf` |").unwrap();
    let g = registry.find("| `g` |").unwrap();
    assert!(cf < g);
    assert!(registry.contains("[`file:///home/rektide/src/compfuzor/README.md`](file:///home/rektide/src/compfuzor/README.md)"));
    success(run(root, &["codes", "--check"]));

    fs::write(
        root.join("codes/g.md"),
        "---\ncode: g\ntarget: /constitution/structure.md#global\ndescription: Changed note.\n---\n\n# g\n\nnotes\n",
    )
    .unwrap();
    let output = run(root, &["codes", "--check"]);
    assert!(!output.status.success());
    assert!(String::from_utf8_lossy(&output.stderr).contains("stale"));

    fs::write(
        root.join("codes/broken.md"),
        "---\ncode: other\ntarget: /x.md\ndescription: mismatched stem\n---\n\n# other\n",
    )
    .unwrap();
    let output = run(root, &["codes", "--check"]);
    assert!(!output.status.success());
    assert!(String::from_utf8_lossy(&output.stderr).contains("must match the file name stem"));
}
