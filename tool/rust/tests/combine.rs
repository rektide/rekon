//! Complete runtime proof for the enriched assembly engine: a full fixture,
//! frontmatter roundtrip through MDX parsing, atomic publication, byte-exact
//! freshness checks, and failures that never touch the filesystem.

use std::fs;
use std::path::{Path, PathBuf};

use rekon::assembly::{AssemblyError, CheckResult, assemble, check_assembly, write_assembly};
use rekon::manifest::ManifestError;

const ALPHA_BODY: &str = r#"# Alpha guide

Intro with {braces} and an autolink <https://example.com/x> plus a comment.

<!-- a provenance note -->

## Details

### Deep

<dl>
<dt><dfn id="term">Term</dfn></dt>
<dd>{kept} definition.</dd>
</dl>

```sh
# not a heading
echo "{raw}"
```

[used]: /used.md
[unused]: /unused.md

See [used] and [root](/root.md) and [term](#term).
"#;

const BETA_BODY: &str = r#"# Beta doc

<dl>
<dt><dfn id="beta-term">Beta term</dfn></dt>
<dd>Beta definition.</dd>
</dl>

## Beta section

More.
"#;

fn alpha_source() -> String {
    format!(
        "---\nid: alpha\norder: 10\nsource: /alpha/README.md\nstatus: stable\n\
         title: Alpha Document\ntags: [one, two]\nempty: null\n---\n\n{ALPHA_BODY}"
    )
}

fn beta_source() -> String {
    format!(
        "---\nid: beta\norder: 20\nsource: /beta/GLOBAL.md\nstatus: draft\n\
         keep:\n  nested: {{ leaf: true }}\n  list: [1, 2]\n---\n\n{BETA_BODY}"
    )
}

/// Write files (creating parents), then a manifest selecting `fragments`.
fn create_bundle(
    root: &Path,
    files: &[(&str, String)],
    fragments: &[&str],
    output: &str,
) -> PathBuf {
    for (path, contents) in files {
        let target = root.join(path);
        fs::create_dir_all(target.parent().unwrap()).unwrap();
        fs::write(target, contents).unwrap();
    }
    let manifest = root.join("bundle/manifest.json");
    fs::create_dir_all(manifest.parent().unwrap()).unwrap();
    let declared: Vec<String> = fragments.iter().map(|path| format!("\"{path}\"")).collect();
    fs::write(
        &manifest,
        format!(
            "{{\"fragments\":[{}],\"output\":\"{output}\"}}",
            declared.join(",")
        ),
    )
    .unwrap();
    manifest
}

fn assemble_fixture(
    root: &Path,
    fragments: &[&str],
    output: &str,
) -> Result<rekon::assembly::Assembly, AssemblyError> {
    let manifest = create_bundle(
        root,
        &[
            ("bundle/alpha.md", alpha_source()),
            ("bundle/beta.md", beta_source()),
        ],
        fragments,
        output,
    );
    assemble(&manifest, root, None)
}

#[test]
fn enriches_a_complete_runtime_fixture() {
    let fixture = tempfile::tempdir().unwrap();
    // Declared beta-first; metadata order must win.
    let assembly =
        assemble_fixture(fixture.path(), &["beta.md", "alpha.md"], "out/AGENTS.md").unwrap();

    let document = &assembly.document;
    // One document H1 with visible generated-file ownership prose; real MDX,
    // so no legacy HTML comments.
    assert!(document.starts_with(
        "# Rekon operating context\n\nThis document is generated by Rust `rekon combine`"
    ));
    assert!(!document.contains("<!--"));
    assert_eq!(
        rekon_markup::parse_document(document).unwrap().headings[0],
        rekon_markup::Heading {
            depth: 1,
            text: "Rekon operating context".into(),
            span: rekon_markup::SourceRange { start: 0, end: 25 }
        }
    );
    assert!(
        document.ends_with("</section>\n"),
        "single trailing newline"
    );
    let alpha = document.find("<section id=\"alpha\"").unwrap();
    let beta = document.find("<section id=\"beta\"").unwrap();
    assert!(alpha < beta, "metadata order, not declaration order");

    // Root section wrapper records the actual selected fragment path, while
    // the frontmatter `source` metadata stays unchanged inside Okf data,
    // including unknown fields, nested objects, arrays, and null.
    let alpha_section = &document[alpha..];
    assert!(
        alpha_section
            .starts_with("<section id=\"alpha\" data-source=\"/alpha.md\">\n\n<Okf data={")
    );
    for expected in [
        "\"id\":\"alpha\"",
        "\"order\":10",
        "\"source\":\"/alpha/README.md\"",
        "\"status\":\"stable\"",
        "\"title\":\"Alpha Document\"",
        "\"tags\":[\"one\",\"two\"]",
        "\"empty\":null",
    ] {
        assert!(alpha_section.contains(expected), "missing {expected}");
    }

    // Heading shift, nested semantic sections with deterministic IDs, escapes.
    assert!(document.contains(
        "\n\n## Alpha guide\n\nIntro with \\{braces\\} and an autolink \
         [https://example.com/x](https://example.com/x) plus a comment.\n\n\
         {/* a provenance note */}\n\n\
         <section id=\"alpha--details\">\n\n### Details\n\n\
         <section id=\"alpha--details--deep\">\n\n#### Deep\n\n<dl>"
    ));
    assert!(document.contains("<dd>{kept} definition.</dd>"));

    // Code is opaque: hash lines and braces inside fences are never touched,
    // and validated reference definitions (used or not) survive verbatim.
    assert!(document.contains("\n```sh\n# not a heading\necho \"{raw}\"\n```\n"));
    assert!(document.contains(
        "[used]: /used.md\n[unused]: /unused.md\n\nSee [used] and [root](/root.md) and [term](#term)."
    ));

    // Closing wrappers: innermost sections first, then the fragment section,
    // with exactly one blank line between sibling fragments.
    assert!(document.contains(
        "and [term](#term).\n\n</section>\n\n</section>\n</section>\n\n\
         <section id=\"beta\" data-source=\"/beta.md\">"
    ));
    assert!(document.contains("\"keep\""));
    assert!(document.contains("\"leaf\":true"));
    assert!(document.contains(
        "<section id=\"beta--beta-section\">\n\n### Beta section\n\nMore.\n\n</section>\n</section>\n"
    ));
    // Source anchor IDs are preserved, never retargeted or renamed.
    assert!(document.contains("<dfn id=\"term\">Term</dfn>"));
    assert_eq!(document.matches("id=\"term\"").count(), 1);

    // Fragment report rows follow metadata order and count source prose bytes.
    let rows = assembly.fragment_reports();
    assert_eq!(rows.len(), 2);
    assert_eq!(rows[0].id, "alpha");
    assert_eq!(rows[0].order, 10);
    assert_eq!(rows[0].path, "alpha.md");
    assert!(rows[0].prose_bytes > 0);
    assert_eq!(rows[1].id, "beta");
    assert_eq!(rows[1].prose_bytes, BETA_BODY.trim().len());
    assert_eq!(assembly.total_bytes(), assembly.document.len());
}

#[test]
fn output_parses_as_mdx_and_frontmatter_roundtrips() {
    let fixture = tempfile::tempdir().unwrap();
    let assembly = assemble_fixture(fixture.path(), &["alpha.md", "beta.md"], "AGENTS.md").unwrap();

    let parsed = rekon_markup::parse_document(&assembly.document).unwrap();
    assert_eq!(parsed.metadata.len(), 2);
    // The published document carries no frontmatter of its own; both scoped
    // records are extracted from the emitted Okf elements, owned by the
    // generated root sections.
    let alpha = &parsed.metadata[0];
    assert_eq!(alpha.origin, rekon_markup::MetadataOrigin::OkfElement);
    assert_eq!(alpha.owner.data_source.as_deref(), Some("/alpha.md"));
    assert_eq!(alpha.metadata["id"], "alpha");
    assert_eq!(alpha.metadata["tags"][0], "one");
    assert_eq!(alpha.metadata["source"], "/alpha/README.md");
    let beta = &parsed.metadata[1];
    assert_eq!(beta.origin, rekon_markup::MetadataOrigin::OkfElement);
    assert_eq!(beta.owner.data_source.as_deref(), Some("/beta.md"));
    assert_eq!(beta.metadata["keep"]["nested"]["leaf"], true);

    let headings: Vec<(String, u8)> = parsed
        .headings
        .iter()
        .map(|heading| (heading.text.clone(), heading.depth))
        .collect();
    for expected in [("Alpha guide", 2u8), ("Deep", 4), ("Beta section", 3)] {
        assert!(
            headings
                .iter()
                .any(|(text, depth)| text == expected.0 && *depth == expected.1),
            "headings: {headings:?}"
        );
    }
}

#[test]
fn write_publishes_atomically_and_check_reports_byte_details() {
    let fixture = tempfile::tempdir().unwrap();
    let root = fixture.path();
    let manifest = create_bundle(
        root,
        &[("bundle/alpha.md", alpha_source())],
        &["alpha.md"],
        "deep/out/AGENTS.md",
    );
    let assembly = assemble(&manifest, root, None).unwrap();
    // Declared outputs resolve from the manifest's directory.
    let output = root.join("bundle/deep/out/AGENTS.md");

    // Checking a missing output is stale and creates nothing.
    assert_eq!(check_assembly(&assembly).unwrap(), CheckResult::Missing);
    assert!(!root.join("bundle/deep").exists());

    write_assembly(&assembly).unwrap();
    assert_eq!(fs::read(&output).unwrap(), assembly.document.as_bytes());
    assert_eq!(check_assembly(&assembly).unwrap(), CheckResult::Fresh);

    let expected_bytes = assembly.document.len();
    let mut corrupted = assembly.document.clone().into_bytes();
    let middle = expected_bytes / 2;
    corrupted[middle] = corrupted[middle].wrapping_add(1);
    fs::write(&output, &corrupted).unwrap();
    assert_eq!(
        check_assembly(&assembly).unwrap(),
        CheckResult::Stale {
            first_difference: middle,
            expected_bytes,
            actual_bytes: expected_bytes
        }
    );

    fs::write(&output, &assembly.document.as_bytes()[..expected_bytes - 3]).unwrap();
    assert_eq!(
        check_assembly(&assembly).unwrap(),
        CheckResult::Stale {
            first_difference: expected_bytes - 3,
            expected_bytes,
            actual_bytes: expected_bytes - 3
        }
    );

    fs::remove_file(&output).unwrap();
    assert_eq!(check_assembly(&assembly).unwrap(), CheckResult::Missing);

    // A directory at the output path is a platform error, not staleness.
    fs::create_dir_all(&output).unwrap();
    assert!(matches!(
        check_assembly(&assembly),
        Err(AssemblyError::Io { .. })
    ));
    assert!(matches!(
        write_assembly(&assembly),
        Err(AssemblyError::Publication { .. })
    ));
}

#[test]
fn validation_failures_leave_the_filesystem_untouched() {
    let cases: Vec<(String, String)> = vec![
        (
            "metadata order must be numeric".into(),
            "---\nid: a\norder: \"10\"\nsource: /a.md\nstatus: draft\n---\n\n# A\n\nbody\n".into(),
        ),
        (
            "bodies must lead with one meaningful H1".into(),
            "---\nid: a\norder: 10\nsource: /a.md\nstatus: draft\n---\n\nJust prose.\n".into(),
        ),
        (
            "fragment-relative links retarget".into(),
            "---\nid: a\norder: 10\nsource: /a.md\nstatus: draft\n---\n\n# A\n\nsee [x](y.md)\n".into(),
        ),
        (
            "unused relative reference definitions retarget".into(),
            "---\nid: a\norder: 10\nsource: /a.md\nstatus: draft\n---\n\n# A\n\n[u]: rel.md\n\nsee [x](/ok.md)\n".into(),
        ),
        (
            "html hrefs are checked too".into(),
            "---\nid: a\norder: 10\nsource: /a.md\nstatus: draft\n---\n\n# A\n\n<a href=\"y.md\">x</a>\n".into(),
        ),
        (
            "depth six would shift past H6".into(),
            "---\nid: a\norder: 10\nsource: /a.md\nstatus: draft\n---\n\n# A\n\n###### Six\n".into(),
        ),
        (
            "reserved toc id".into(),
            "---\nid: a\norder: 10\nsource: /a.md\nstatus: draft\n---\n\n# A\n\n<a id=\"rekon-toc\"></a>\n".into(),
        ),
        (
            "source anchor collides with its document section".into(),
            "---\nid: a\norder: 10\nsource: /a.md\nstatus: draft\n---\n\n# A\n\n<a id=\"a\"></a>\n".into(),
        ),
    ];
    for (name, raw) in cases {
        let fixture = tempfile::tempdir().unwrap();
        let manifest = create_bundle(
            fixture.path(),
            &[("bundle/a.md", raw)],
            &["a.md"],
            "out/AGENTS.md",
        );
        let error = assemble(&manifest, fixture.path(), None)
            .map(|_| ())
            .expect_err(&name);
        assert!(
            !fixture.path().join("out").exists(),
            "{name} must fail before any filesystem effect: {error}"
        );
    }

    // Cross-fragment identity and anchor collisions fail as assembly errors.
    let duplicate = |fragments: &[&str], files: &[(&str, String)]| -> AssemblyError {
        let fixture = tempfile::tempdir().unwrap();
        let manifest = create_bundle(fixture.path(), files, fragments, "out/AGENTS.md");
        assemble(&manifest, fixture.path(), None).unwrap_err()
    };
    let same_id = |id: &str| {
        (
            format!("bundle/{id}.md"),
            format!(
                "---\nid: {id}\norder: 10\nsource: /{id}.md\nstatus: draft\n---\n\n# {id}\n\nbody\n"
            ),
        )
    };
    assert!(matches!(
        duplicate(
            &["a.md", "b.md"],
            &[
                ("bundle/a.md", same_id("a").1),
                ("bundle/b.md", same_id("a").1)
            ]
        ),
        AssemblyError::DuplicateFragmentId { .. }
    ));
    assert!(matches!(
        duplicate(
            &["a.md", "b.md"],
            &[
                ("bundle/a.md", same_id("a").1),
                ("bundle/b.md", same_id("b").1)
            ]
        ),
        AssemblyError::DuplicateFragmentOrder { .. }
    ));
    let anchored = |path: &str, id: &str, order: i64, body: &str| {
        (
            path.to_string(),
            format!(
                "---\nid: {id}\norder: {order}\nsource: /{id}.md\nstatus: draft\n---\n\n# {id}\n\n{body}\n"
            ),
        )
    };
    assert!(matches!(
        duplicate(
            &["a.md", "b.md"],
            &[
                (
                    "bundle/a.md",
                    anchored("a", "a", 10, "<a id=\"shared\"></a>").1
                ),
                (
                    "bundle/b.md",
                    anchored("b", "b", 20, "<a id=\"shared\"></a>").1
                ),
            ]
        ),
        AssemblyError::DuplicateAnchorId { .. }
    ));
}

#[test]
fn output_never_overwrites_inputs_lexically_or_through_aliases() {
    let fixture = tempfile::tempdir().unwrap();
    let root = fixture.path();
    let manifest = create_bundle(root, &[("bundle/a.md", alpha_source())], &["a.md"], "a.md");
    let error = assemble(&manifest, root, None).unwrap_err();
    assert!(matches!(
        error,
        AssemblyError::Manifest(ManifestError::OutputOverwritesInput { .. })
    ));

    let manifest = create_bundle(
        root,
        &[("bundle/a.md", alpha_source())],
        &["a.md"],
        "manifest.json",
    );
    assert!(matches!(
        assemble(&manifest, root, None),
        Err(AssemblyError::Manifest(
            ManifestError::OutputOverwritesInput { .. }
        ))
    ));

    // A symlinked directory aliasing the fragment file is caught at write time.
    let manifest = create_bundle(
        root,
        &[("bundle/a.md", alpha_source())],
        &["a.md"],
        "out/AGENTS.md",
    );
    let assembly = assemble(&manifest, root, None).unwrap();
    #[cfg(unix)]
    {
        fs::create_dir_all(root.join("bundle/out")).unwrap();
        std::os::unix::fs::symlink(root.join("bundle/a.md"), root.join("bundle/out/AGENTS.md"))
            .unwrap();
        assert!(matches!(
            write_assembly(&assembly),
            Err(AssemblyError::OutputSymlink { .. })
        ));
        assert!(
            fs::symlink_metadata(root.join("bundle/out/AGENTS.md"))
                .unwrap()
                .file_type()
                .is_symlink(),
            "refusal must not touch the symlink"
        );
        fs::remove_file(root.join("bundle/out/AGENTS.md")).unwrap();

        // An output reaching a fragment through a path alias is refused too.
        std::os::unix::fs::symlink(root, root.join("loop")).unwrap();
        let aliased = assemble(&manifest, root, Some(Path::new("loop/bundle/a.md"))).unwrap();
        assert!(matches!(
            write_assembly(&aliased),
            Err(AssemblyError::OutputProtected { .. })
        ));
    }
}

#[test]
fn assembles_deterministically_across_runs() {
    let first = tempfile::tempdir().unwrap();
    let second = tempfile::tempdir().unwrap();
    let left = assemble_fixture(first.path(), &["beta.md", "alpha.md"], "AGENTS.md").unwrap();
    let right = assemble_fixture(second.path(), &["beta.md", "alpha.md"], "AGENTS.md").unwrap();
    assert_eq!(left.document, right.document);
    assert_eq!(left.fragment_reports(), right.fragment_reports());
}

#[test]
fn missing_fragments_and_output_overrides_resolve_from_their_own_roots() {
    let fixture = tempfile::tempdir().unwrap();
    let root = fixture.path();
    let manifest = create_bundle(
        root,
        &[("bundle/a.md", alpha_source())],
        &["a.md"],
        "out/AGENTS.md",
    );
    fs::remove_file(root.join("bundle/a.md")).unwrap();
    let error = assemble(&manifest, root, None).unwrap_err();
    assert!(matches!(error, AssemblyError::Io { .. }), "{error:?}");
    assert!(error.to_string().contains("bundle/a.md"));

    // An explicit override resolves from cwd, not the manifest directory.
    let manifest = create_bundle(
        root,
        &[("bundle/a.md", alpha_source())],
        &["a.md"],
        "out/AGENTS.md",
    );
    let assembly = assemble(&manifest, root, Some(Path::new("preview.md"))).unwrap();
    assert_eq!(assembly.output, root.join("preview.md"));
    write_assembly(&assembly).unwrap();
    assert_eq!(
        fs::read(root.join("preview.md")).unwrap(),
        assembly.document.as_bytes()
    );
    assert!(!root.join("out").exists());
}
